package Valdi.Belajar_Java_Dasar;

public class Konversi {
    public static void main(String[] args) {
        int AngkaInt = 29;  // Nilai awal dalam tipe int
        double AngkaDouble = AngkaInt; // Konversi otomatis ke double

        System.out.println("Nilai int     : " + AngkaInt);
        System.out.println("Setelah jadi double: " + AngkaDouble);
        //int itu bilangan bulat tanpa decimal
        //double itu bilangan decimal
    }
}
